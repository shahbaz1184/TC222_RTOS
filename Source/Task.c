/* ------------------------------------------------------------
 * CSA <-> address conversion
 * A CSA is 64 bytes / 16 words, 64-byte aligned. Bits 31:6 of a
 * PCXI-format value map directly onto bits 31:6 of the linear
 * address; low 6 bits are always 0.
 * ------------------------------------------------------------ */
#define CSA_ADDR_MASK   0xFFFFFFC0u
#define PCXI_UL_BIT     0x00400000u

static inline uint32* csaToAddr(uint32 csa)
{
    return (uint32 *)(((csa & 0x000F0000) << 12) | ((csa & 0x0000FFFF) << 6));
}

static inline uint32 addrToCsa(uint32 *addr)
{
    uint32 a = (uint32)addr;
    return ((a >> 12) & 0x000F0000) | ((a >> 6) & 0x0000FFFF);
}

/* ------------------------------------------------------------
 * CSA pool
 * ------------------------------------------------------------ */
#pragma align 64
static uint32 csaArray[CSA_SIZE * 16];

static Task   taskList[MAX_TASKS];
static uint32 taskStack[MAX_TASKS][STACK_SIZE];
static uint16 taskCount    = 0;
static uint16 currentTask  = 0;

/* ------------------------------------------------------------
 * getTwoCSA — pull two linked CSAs off the FCX free list
 * ------------------------------------------------------------ */
void getTwoCSA(uint32 **lower, uint32 **upper)
{
    uint32 pcxi = __mfcr(CPU_FCX);
    if (pcxi == 0) while (1);              /* pool exhausted */

    *lower = csaToAddr(pcxi);
    pcxi;
    &csaArray[0];
    &csaArray[CSA_SIZE*16-1];

    uint32 next = (*lower)[0];
    if (next == 0) while (1);              /* chain broken / exhausted */

    *upper = csaToAddr(next);

    uint32 newFcx = (*upper)[0];
    if (newFcx == 0) while (1);

    __mtcr(CPU_FCX, newFcx);
    __isync();
}

/* ------------------------------------------------------------
 * osCreateTask — build a task's initial CSA chain
 *
 * Lower context word layout: [0]=PCXI [1]=A11 [2]=A2 [3]=A3
 *   [4..7]=D0-D3 [8..11]=D4-D7 [12..15]=A4-A7
 * Upper context word layout: [0]=PCXI [1]=PSW [2]=A10 [3]=A11
 *   [4..7]=D8-D11 [8..11]=D12-D15 [12..15]=A12-A15
 * ------------------------------------------------------------ */
void osCreateTask(void (*Func)(void), uint16 priority)
{
    if (taskCount >= MAX_TASKS) while (1);

    uint16 id = taskCount;
    uint32 *lowerCSA, *upperCSA;

    getTwoCSA(&lowerCSA, &upperCSA);

    for (int i = 0; i < 16; i++) { lowerCSA[i] = 0; upperCSA[i] = 0; }

    /* Upper context: what rfe restores PC/PSW/SP from */
    upperCSA[0] = 0;                                     /* end of chain */
    upperCSA[1] = 0x00000B80u;                            /* PSW — verify against your reset value */
    upperCSA[2] = (uint32)&taskStack[id][STACK_SIZE];     /* A10 = SP */
    upperCSA[3] = (uint32)Func;                           /* A11 = PC restored by rfe */

    /* Lower context: linked so the hardware has a valid chain if the
     * task itself later calls/traps — not consumed directly by rfe. */
    lowerCSA[0] = addrToCsa(upperCSA) | PCXI_UL_BIT;      /* link -> upper, UL=1 */

    /* Task's saved PCXI points at the UPPER context (UL=1) since
     * rfe consumes an upper context first. */
    taskList[id].pcxi     = addrToCsa(upperCSA) | PCXI_UL_BIT;
    taskList[id].priority = priority;
    taskList[id].used     = 1;

    taskCount++;

    uint32 i = taskList[id].pcxi;
}

/* ------------------------------------------------------------
 * osSwitchContext / osStart
 * ------------------------------------------------------------ */
void osSwitchContext(uint16 id)
{
    currentTask = id;

    uint32 psw = __mfcr(CPU_PSW);
    psw &= 0xFFFFFF00u;          // clear CDE (bit7) and CDC (bits 6:0) — disable call-depth
                                  // checking for this switch, since we're doing our own scheduling
    __mtcr(CPU_PSW, psw);
    __isync();

    __mtcr(CPU_PCXI, taskList[id].pcxi);
    __isync();
    __asm("rfe");
}

void osStart(void)
{
    uint16 best = 0;
    for (uint16 i = 1; i < taskCount; i++)
        if (taskList[i].priority < taskList[best].priority)   /* confirm: lower = higher priority in your scheme */
            best = i;

    osSwitchContext(best);
    /* never returns */
}

/* ------------------------------------------------------------
 * debugCheckUL — run this ONCE, at a breakpoint, after any real
 * interrupt has fired at least once (e.g. your STM tick ISR).
 * It reads whatever PCXI the HARDWARE itself just wrote, and
 * reports whether bit 1 was set. That's ground truth for your
 * exact TC222/TASKING combo — use it to confirm PCXI_UL_BIT above
 * is correct before trusting osCreateTask/osSwitchContext fully.
 * ------------------------------------------------------------ */
uint32 debugCheckUL(void)
{
    uint32 pcxi = __mfcr(CPU_PCXI);
    uint32 ulBitSet = (pcxi & PCXI_UL_BIT) ? 1u : 0u;
    return ulBitSet;   /* inspect this return value / pcxi in the debugger */
}


