IFX_INTERRUPT(STM0_ISR, 0, ISR_PRIORITY_STM);

void STM0_ISR(void)
{
    uint32 now = IfxStm_get(STM);

    /* Catch-up logic: ensure we don't miss ticks */
    do
    {
        nextCompare += ticksPerOsTick;
    }
    while (nextCompare <= now);

    IfxStm_updateCompare(STM, gComparator, nextCompare);

    /* FreeRTOS tick */
    if (xTaskIncrementTick() != pdFALSE)
    {
        portYIELD();
    }

}
